#!/usr/bin/env python3
"""Regenerate app/src/debug/assets/demo_routes.json (debug-only demo drive routes).

Road routes from Suwon station through the five TourCatalog places, from the public
OSRM server (OpenStreetMap data), thinned to a point every ~40 m. Needs network and curl.
  python3 tools/make_demo_routes.py
"""
import json, math, os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "app/src/main/java/com/team/carescape/game/TourCatalog.kt")
OUT = os.path.join(ROOT, "app/src/debug/assets/demo_routes.json")
START = (37.265506, 127.000215)  # Suwon station: where the demo trip begins


def hav(a, b):
    r = 6371000
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    h = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(b[1] - a[1]) / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def thin(line, step=40):
    out, acc = [line[0]], 0.0
    for p in line[1:]:
        acc += hav(out[-1], p)
        if acc >= step:
            out.append(p); acc = 0.0
    if out[-1] != line[-1]:
        out.append(line[-1])
    return out


def main():
    text = open(CATALOG, encoding="utf-8").read()
    places = [(float(a), float(b)) for a, b in re.findall(r'WaypointConfig\("[^"]+",\s*"[^"]+",\s*([0-9.]+),\s*([0-9.]+)', text)]
    stops = [START] + places
    legs = []
    for i in range(len(places)):
        a, b = stops[i], stops[i + 1]
        url = f"https://router.project-osrm.org/route/v1/driving/{a[1]},{a[0]};{b[1]},{b[0]}?overview=full&geometries=geojson"
        data = json.loads(subprocess.run(["curl", "-s", "-m", "20", "-A", "route-sim-dev/0.1", url], capture_output=True, text=True).stdout)
        route = data["routes"][0]
        line = thin([(round(lat, 6), round(lon, 6)) for lon, lat in route["geometry"]["coordinates"]]) + [b]
        legs.append({"chapterIndex": i, "distanceM": round(route["distance"]), "points": line})
        print(f"leg {i + 1}: {route['distance'] / 1000:.1f} km, {len(line)} points")
    json.dump({"source": "OSRM (OpenStreetMap) road routes, generated by tools/make_demo_routes.py; demo only",
               "start": START, "legs": legs}, open(OUT, "w"), separators=(",", ":"))


if __name__ == "__main__":
    main()
